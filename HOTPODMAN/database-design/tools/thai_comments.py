LABELS = {k.strip().removeprefix('a '): v for k,v in LABELS.items()}

def annotate(tables):
    by={t['name']:t for t in tables}
    for t in tables:
        t['comment_th']='ตารางเก็บข้อมูล '+t['grain']+'; หนึ่งแถวมีความหมายตามนี้และอยู่ในเฟส '+t['phase']
        t['primary_key']=['id']
        for c in t['columns']:
            n=c['name'];typ=c['type'];ref=c['reference']
            if ref:
                parent=ref.rsplit('.',1)[0]
                role=LABELS.get(n)
                role=role or {'created_by':'ผู้สร้าง','confirmed_by':'ผู้ยืนยัน','requested_by':'ผู้ร้องขอ','validated_by':'ผู้ตรวจรับ','approved_by':'ผู้อนุมัติ','reviewed_by':'ผู้ตรวจทาน','actor_id':'ผู้ดำเนินการ','from_account_id':'บัญชีสต็อกต้นทาง','to_account_id':'บัญชีสต็อกปลายทาง','source_account_id':'บัญชีสต็อกต้นทาง','destination_account_id':'บัญชีสต็อกปลายทาง','company_id':'บริษัทเจ้าของข้อมูล','branch_id':'สาขาเจ้าของรายการ','warehouse_id':'คลังที่เกี่ยวข้อง','product_id':'สินค้าในรายการ','supplier_id':'ผู้ขายในรายการ'}.get(n)
                desc=('รหัสอ้างอิง'+role if role else 'รหัสอ้างอิง '+by[parent]['grain'])+' ไปยัง '+ref+' (บทบาทฟิลด์ '+n+')'
            else:
                if n not in LABELS: raise ValueError(f'Missing Thai explanation: {t["name"]}.{n}')
                desc=LABELS[n]
            if typ=='timestamptz':desc+='; เป็นเวลาเหตุการณ์จริง เก็บ UTC ส่ง API เป็น ISO 8601 มี Z แสดงตาม timezone ธุรกิจ เช่น Asia/Bangkok'
            elif typ=='date':desc+='; เป็นวันที่ปฏิทินธุรกิจ YYYY-MM-DD ไม่มีเวลาและไม่เลื่อนวันด้วย timezone'
            elif typ.startswith('numeric('):desc+='; เลขทศนิยมแม่นยำ ส่ง API เป็น string ไม่คำนวณด้วย float'
            elif typ=='jsonb':desc+='; ต้องตรวจ schema และจำกัดข้อมูลตามสิทธิ์'
            if n=='id':desc+='; Primary Key ชนิด UUID ห้ามซ้ำหรือเป็น NULL'
            c['comment_th']=desc
            c['key_role']='PK' if n=='id' else 'FK' if ref else '—'
